function clamp(val, min, max) {
  return Math.max(min, Math.min(max, val));
}

function smoothstep(edge0, edge1, x) {
  const t = clamp((x - edge0) / (edge1 - edge0), 0, 1);
  return t * t * (3 - 2 * t);
}

export function mapGazeToFrame(gx, gy, mode = 'spatial', clipId = 'clip1') {
  const x = clamp(gx, -1, 1);
  const y = clamp(gy, -1, 1);

  if (mode === 'linear') {
    if (Math.abs(x) < 0.03) return { frame: 0, branch: 'center' };
    if (x < 0) {
      return {
        frame: Math.abs(x) * 28,
        branch: 'left-mid',
      };
    }
    return {
      frame: 100 + x * 26,
      branch: 'right-mid',
    };
  }

  const radial = clamp(Math.hypot(x, y * 0.85), 0, 1);
  if (radial < 0.04) {
    return { frame: 0, branch: 'center' };
  }

  if (x >= 0) {
    if (clipId === 'clip2' && y < -0.22 && x > 0.12) {
      const upRightMag = clamp(Math.hypot(x * 0.9, y * 0.9), 0, 1);
      const t = smoothstep(0.05, 0.95, upRightMag);
      return {
        frame: 186 - t * 20,
        branch: 'right-up-clip2',
      };
    }

    const rightHorizMag =
      y < 0
        ? clamp(Math.hypot(x, -y * 0.55), 0, 1)
        : clamp(x * 1.12, 0, 1);
    const baseRight = 100 + smoothstep(0.02, 0.95, rightHorizMag) * 26;

    if (y > 0.14) {
      const downT =
        smoothstep(0.14, 0.88, y) * smoothstep(0.08, 0.45, x);
      return {
        frame: clamp(baseRight + downT * 18, 100, 144),
        branch: 'right-main',
      };
    }

    return {
      frame: clamp(baseRight, 100, 126),
      branch: 'right-main',
    };
  }

  const absX = Math.abs(x);

  if (y < -0.18) {
    const upLeftMag = clamp(Math.hypot(absX * 0.9, -y * 0.95), 0, 1);
    const t = smoothstep(0.04, 0.95, upLeftMag);
    return {
      frame: clamp(92 - t * 26, 66, 92),
      branch: 'left-up',
    };
  }

  const leftHorizT = smoothstep(0.02, 0.95, clamp(absX * 1.12, 0, 1));
  const baseLeft = leftHorizT * 28;

  if (y > 0.14) {
    const downT =
      smoothstep(0.14, 0.88, y) * smoothstep(0.08, 0.45, absX);
    return {
      frame: clamp(baseLeft + downT * 17, 0, 45),
      branch: 'left-main',
    };
  }

  return {
    frame: clamp(baseLeft, 0, 28),
    branch: 'left-main',
  };
}

export function getGazeDirectionLabel(nx, ny, isTracking) {
  if (!isTracking) return 'IDLE · CENTER GAZE';
  const dist = Math.hypot(nx, ny);
  if (dist < 0.1) return 'LOCKED · CENTER';

  const horiz = nx < -0.15 ? 'LEFT' : nx > 0.15 ? 'RIGHT' : '';
  const vert = ny < -0.18 ? 'UPPER' : ny > 0.18 ? 'LOWER' : '';

  if (vert && horiz) return `XO TRACK · ${vert}-${horiz}`;
  if (horiz) return `XO TRACK · ${horiz}`;
  if (vert) return `XO TRACK · ${vert}`;
  return 'XO TRACK · CENTER';
}
