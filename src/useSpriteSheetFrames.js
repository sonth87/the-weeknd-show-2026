import { useEffect, useRef, useState, useCallback } from 'react';
import { CLIPS } from './clipsConfig';

// Module-level persistent frame store so switching clips is instant
const globalClipStore = new Map();

function getOrCreateClipEntry(clip) {
  if (!globalClipStore.has(clip.id)) {
    globalClipStore.set(clip.id, {
      frames: new Array(clip.totalFrames).fill(null),
      hdLoadedCount: 0,
      sheetSliced: false,
      loadingPromise: null,
      listeners: new Set(),
    });
  }
  return globalClipStore.get(clip.id);
}

function notifyListeners(entry) {
  const progress = Math.min(
    100,
    Math.round(
      ((entry.sheetSliced ? 35 : 0) +
        (entry.hdLoadedCount / 192) * 65)
    )
  );
  const ready = entry.sheetSliced || entry.hdLoadedCount > 12;
  entry.listeners.forEach((cb) =>
    cb({
      progress,
      ready,
      sheetSliced: entry.sheetSliced,
      hdLoadedCount: entry.hdLoadedCount,
    })
  );
}

function loadImage(url) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.decoding = 'async';
    img.onload = () => resolve(img);
    img.onerror = (err) => reject(err);
    img.src = url;
  });
}

/**
 * Slices a horizontal sprite sheet (Nx1) into individual offscreen canvas frames
 * using CPU-backed 2D context so we never exceed WebGL/Metal MAX_TEXTURE_SIZE.
 */
function sliceHorizontalSpriteSheet(img, frameCount, frameW, frameH, stepMultiplier = 1) {
  const sliced = [];
  for (let i = 0; i < frameCount; i++) {
    const canvas = document.createElement('canvas');
    canvas.width = frameW;
    canvas.height = frameH;
    const ctx = canvas.getContext('2d');
    ctx.drawImage(
      img,
      i * frameW,
      0,
      frameW,
      frameH,
      0,
      0,
      frameW,
      frameH
    );
    sliced.push({ index: i * stepMultiplier, canvas });
  }
  return sliced;
}

async function loadClipResources(clip) {
  const entry = getOrCreateClipEntry(clip);
  if (entry.loadingPromise) return entry.loadingPromise;

  entry.loadingPromise = (async () => {
    // 1. Immediately load the exact Idle Pose frame (frame 96 -> frame_097.jpg)
    try {
      const idleImg = await loadImage(clip.posterUrl);
      entry.frames[clip.idleFrame] = idleImg;
      entry.hdLoadedCount += 1;
      notifyListeners(entry);
    } catch {
      // Fallback handled by sheet below
    }

    // 2. Load the GPU-safe horizontal sprite sheet strip (96x1 -> covers frames 0..191)
    // and slice every frame so scrubbing works immediately across all 192 active frames
    try {
      const previewSheet = await loadImage(clip.previewStripUrl);
      const slices = sliceHorizontalSpriteSheet(
        previewSheet,
        clip.previewStripFrames,
        clip.previewFrameWidth,
        clip.previewFrameHeight,
        2
      );
      for (const { index, canvas } of slices) {
        if (!entry.frames[index]) {
          entry.frames[index] = canvas;
        }
        if (index + 1 < clip.totalFrames && !entry.frames[index + 1]) {
          entry.frames[index + 1] = canvas;
        }
      }
      entry.sheetSliced = true;
      notifyListeners(entry);
    } catch {
      // Continue to full sheet & HD frames
    }

    // 3. Also load the full 240x1 horizontal sprite sheet generated by FFmpeg
    loadImage(clip.spriteSheetUrl)
      .then((fullSheet) => {
        // Fill any remaining frames (192..239) from the 240x1 sheet if not yet HD
        for (let i = 0; i < clip.totalFrames; i++) {
          if (!entry.frames[i] || entry.frames[i].width === clip.previewFrameWidth) {
            const c = document.createElement('canvas');
            c.width = clip.sheetFrameWidth;
            c.height = clip.sheetFrameHeight;
            const ctx = c.getContext('2d');
            ctx.drawImage(
              fullSheet,
              i * clip.sheetFrameWidth,
              0,
              clip.sheetFrameWidth,
              clip.sheetFrameHeight,
              0,
              0,
              clip.sheetFrameWidth,
              clip.sheetFrameHeight
            );
            // Only overwrite if an HD 540x960 HTMLImageElement hasn't already taken the slot
            if (!(entry.frames[i] instanceof HTMLImageElement)) {
              entry.frames[i] = c;
            }
          }
        }
        entry.sheetSliced = true;
        notifyListeners(entry);
      })
      .catch(() => {});

    // 4. Progressively upgrade active frames (0..192) to full 540x960 HD resolution
    // Prioritize frames outward from the idle pose (96) and key directional poses
    const frameOrder = [];
    const seen = new Set([clip.idleFrame]);

    // Add key directional landmarks first
    const landmarks = [96, 26, 44, 68, 124, 142, 166, 0, 84, 108, 184];
    for (const lm of landmarks) {
      if (!seen.has(lm)) {
        seen.add(lm);
        frameOrder.push(lm);
      }
    }

    // Expand outward from idleFrame (96)
    for (let offset = 1; offset <= 96; offset++) {
      const left = clip.idleFrame - offset;
      const right = clip.idleFrame + offset;
      if (left >= 0 && !seen.has(left)) {
        seen.add(left);
        frameOrder.push(left);
      }
      if (right < clip.activeFrames && !seen.has(right)) {
        seen.add(right);
        frameOrder.push(right);
      }
    }

    const concurrency = 12;
    let cursor = 0;

    async function worker() {
      while (cursor < frameOrder.length) {
        const frameIdx = frameOrder[cursor++];
        const padded = String(frameIdx + 1).padStart(3, '0');
        const url = `${clip.framesBaseUrl}/frame_${padded}.jpg`;
        try {
          const hdImg = await loadImage(url);
          entry.frames[frameIdx] = hdImg;
          entry.hdLoadedCount += 1;
          if (entry.hdLoadedCount % 8 === 0 || entry.hdLoadedCount >= 188) {
            notifyListeners(entry);
          }
        } catch {
          // Keep sprite-sheet slice fallback
        }
      }
    }

    await Promise.all(Array.from({ length: concurrency }, () => worker()));
    notifyListeners(entry);
  })();

  return entry.loadingPromise;
}

export function useSpriteSheetFrames(activeClip) {
  const entry = getOrCreateClipEntry(activeClip);
  const [status, setStatus] = useState(() => ({
    progress: Math.min(
      100,
      Math.round(
        ((entry.sheetSliced ? 35 : 0) + (entry.hdLoadedCount / 192) * 65)
      )
    ),
    ready: entry.sheetSliced || entry.hdLoadedCount > 0,
    sheetSliced: entry.sheetSliced,
    hdLoadedCount: entry.hdLoadedCount,
  }));

  const framesRef = useRef(entry.frames);
  framesRef.current = entry.frames;

  useEffect(() => {
    const currentEntry = getOrCreateClipEntry(activeClip);
    framesRef.current = currentEntry.frames;

    const handleUpdate = (nextStatus) => {
      setStatus(nextStatus);
    };

    currentEntry.listeners.add(handleUpdate);
    notifyListeners(currentEntry);

    // Load active clip first, then warm up the second clip in background
    loadClipResources(activeClip).then(() => {
      CLIPS.forEach((otherClip) => {
        if (otherClip.id !== activeClip.id) {
          loadClipResources(otherClip);
        }
      });
    });

    return () => {
      currentEntry.listeners.delete(handleUpdate);
    };
  }, [activeClip]);

  const getFrameDrawable = useCallback(
    (frameIndex) => {
      const list = framesRef.current;
      const idx = Math.max(0, Math.min(activeClip.totalFrames - 1, Math.round(frameIndex)));
      if (list[idx]) return list[idx];
      // Nearest loaded neighbor fallback
      for (let delta = 1; delta < 24; delta++) {
        if (idx - delta >= 0 && list[idx - delta]) return list[idx - delta];
        if (idx + delta < list.length && list[idx + delta]) return list[idx + delta];
      }
      return list[activeClip.idleFrame] || null;
    },
    [activeClip]
  );

  return {
    ...status,
    getFrameDrawable,
  };
}
